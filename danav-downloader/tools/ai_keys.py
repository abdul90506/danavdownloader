"""Seal the Danav AI API keys into AiKeys.java.
Usage: python3 ai_keys.py <keys.txt>   (one key per line; the file is NOT kept in the project)
Keys are XOR-sealed with a SHA-256 keystream derived from the APK signing certificate, so they
never appear as plain text in the APK and do not open in a re-signed (tampered) copy."""
import sys, os, hashlib, hmac, base64, subprocess
CERT_SHA256 = '91631a240b93e97ad5c3d615bcf420653d9a61811d68ad864b9fab93667b2b87'
SALT = 'd4n4v-41|dilhan'
keys = [k.strip() for k in open(sys.argv[1]) if k.strip()]
master = hashlib.sha256(('danav.ai/v1|' + CERT_SHA256 + '|' + SALT).encode()).digest()
def stream(nonce, n):
    out = b''; c = 0
    while len(out) < n:
        out += hashlib.sha256(master + nonce + c.to_bytes(4, 'big')).digest(); c += 1
    return out[:n]
blobs = []
for k in keys:
    nonce = os.urandom(12); kb = k.encode()
    ct = bytes(a ^ b for a, b in zip(kb, stream(nonce, len(kb))))
    tag = hmac.new(master, nonce + ct, hashlib.sha256).digest()[:8]
    blobs.append(base64.b64encode(nonce + ct + tag).decode())
java = f'''package com.dilhan.vidra;

import android.content.Context;
import android.content.pm.PackageManager;
import android.content.pm.Signature;
import android.os.Build;
import android.util.Base64;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.List;
import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;

/** Danav AI keys — sealed (generated by tools/ai_keys.py). They are opened only in memory, on the native side,
 *  and only inside an APK signed with Danav's own certificate. The web UI never sees them. */
final class AiKeys {{
    private static final String[] SEALED = {{
{chr(10).join('            "' + b + '",' for b in blobs)}
    }};
    private static final String SALT = "{SALT}";
    private static List<String> keys;
    static String certSha1 = "";

    static synchronized List<String> get(Context c) {{
        if (keys != null) return keys;
        List<String> out = new ArrayList<>();
        try {{
            byte[] cert = cert(c);
            certSha1 = hex(MessageDigest.getInstance("SHA-1").digest(cert)).toUpperCase(java.util.Locale.ROOT);
            String certHex = hex(MessageDigest.getInstance("SHA-256").digest(cert));
            byte[] master = MessageDigest.getInstance("SHA-256").digest(("danav.ai/v1|" + certHex + "|" + SALT).getBytes("UTF-8"));
            Mac mac = Mac.getInstance("HmacSHA256"); mac.init(new SecretKeySpec(master, "HmacSHA256"));
            for (String s : SEALED) {{
                byte[] b = Base64.decode(s, Base64.NO_WRAP);
                int n = b.length - 12 - 8;
                mac.update(b, 0, 12 + n);
                byte[] tag = mac.doFinal();
                boolean ok = true;
                for (int i = 0; i < 8; i++) ok &= tag[i] == b[12 + n + i];
                if (!ok) continue;
                byte[] ks = stream(master, b, n), pt = new byte[n];
                for (int i = 0; i < n; i++) pt[i] = (byte) (b[12 + i] ^ ks[i]);
                out.add(new String(pt, "UTF-8"));
            }}
        }} catch (Exception ignored) {{}}
        keys = out;
        return keys;
    }}

    private static byte[] stream(byte[] master, byte[] nonceSrc, int n) throws Exception {{
        byte[] out = new byte[n];
        int off = 0, ctr = 0;
        while (off < n) {{
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            md.update(master); md.update(nonceSrc, 0, 12);
            md.update(new byte[]{{(byte) (ctr >>> 24), (byte) (ctr >>> 16), (byte) (ctr >>> 8), (byte) ctr}});
            byte[] blk = md.digest();
            int k = Math.min(32, n - off);
            System.arraycopy(blk, 0, out, off, k);
            off += k; ctr++;
        }}
        return out;
    }}

    @SuppressWarnings("deprecation")
    private static byte[] cert(Context c) throws Exception {{
        PackageManager pm = c.getPackageManager();
        Signature[] sigs;
        if (Build.VERSION.SDK_INT >= 28) sigs = pm.getPackageInfo(c.getPackageName(), PackageManager.GET_SIGNING_CERTIFICATES).signingInfo.getApkContentsSigners();
        else sigs = pm.getPackageInfo(c.getPackageName(), PackageManager.GET_SIGNATURES).signatures;
        return sigs[0].toByteArray();
    }}

    private static String hex(byte[] b) {{ StringBuilder s = new StringBuilder(); for (byte x : b) s.append(String.format("%02x", x)); return s.toString(); }}
}}
'''
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../app/src/main/java/com/dilhan/vidra/AiKeys.java'), 'w').write(java)
print('sealed', len(blobs), 'keys')
